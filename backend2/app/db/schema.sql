-- Orion v2 — Phase 1 database schema.
-- Standard-library sqlite3 only. WAL mode enabled in sqlite.py.
-- All timestamps are UTC ISO-8601 strings. JSON columns store serialized dicts/lists.

CREATE TABLE IF NOT EXISTS missions (
    id            TEXT PRIMARY KEY,
    prompt        TEXT NOT NULL,
    title         TEXT,                      -- short name generated by the planner
    status        TEXT NOT NULL,             -- planning | running | completed | failed | partial
    department_id TEXT,                       -- optional; routes to a department's agents
    conversation_id TEXT,                     -- optional; links a mission to a chat turn
    created_by    TEXT NOT NULL,             -- user_id (Phase 1: 'default-user')
    created_at    TEXT NOT NULL,
    completed_at  TEXT
);

CREATE INDEX IF NOT EXISTS idx_missions_created ON missions(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_missions_status  ON missions(status);

CREATE TABLE IF NOT EXISTS mission_tasks (
    id           TEXT PRIMARY KEY,
    mission_id   TEXT NOT NULL,
    title        TEXT NOT NULL,
    agent_type   TEXT NOT NULL,
    agent_id     TEXT,                        -- assigned by the router
    tools_needed TEXT NOT NULL DEFAULT '[]',  -- json array
    depends_on   TEXT NOT NULL DEFAULT '[]',  -- json array of task titles
    status       TEXT NOT NULL,               -- pending | running | completed | failed
    result       TEXT,                        -- json {summary, data}
    created_at   TEXT NOT NULL,
    completed_at TEXT,
    FOREIGN KEY (mission_id) REFERENCES missions(id)
);

CREATE INDEX IF NOT EXISTS idx_tasks_mission ON mission_tasks(mission_id);

CREATE TABLE IF NOT EXISTS execution_traces (
    id            TEXT PRIMARY KEY,
    mission_id    TEXT NOT NULL,
    task_id       TEXT NOT NULL,
    agent_id      TEXT NOT NULL,
    trace_type    TEXT NOT NULL,              -- llm | tool
    provider      TEXT,                        -- groq | gemini | ollama | openai
    model         TEXT,
    input_tokens  INTEGER,
    output_tokens INTEGER,
    cost_usd      REAL,
    tool_name     TEXT,
    tool_input    TEXT,                        -- json
    tool_output   TEXT,                        -- json
    latency_ms    INTEGER,
    success       INTEGER NOT NULL,            -- 1 | 0
    error_message TEXT,
    created_at    TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_traces_mission ON execution_traces(mission_id);
CREATE INDEX IF NOT EXISTS idx_traces_agent   ON execution_traces(agent_id);

CREATE TABLE IF NOT EXISTS agents (
    id             TEXT PRIMARY KEY,
    name           TEXT NOT NULL,
    purpose        TEXT,
    system_prompt  TEXT NOT NULL,
    agent_type     TEXT NOT NULL,             -- research | marketing | finance | operations | hr | analysis | writing | general
    tools          TEXT NOT NULL DEFAULT '[]',  -- json array of tool ids
    sub_agents     TEXT NOT NULL DEFAULT '[]',  -- json array of agent ids
    department_id  TEXT,
    model          TEXT NOT NULL DEFAULT 'groq:llama-3.1-8b-instant',
    temperature    REAL NOT NULL DEFAULT 0.7,
    memory_enabled INTEGER NOT NULL DEFAULT 0,
    permissions    TEXT NOT NULL DEFAULT '{}',  -- json
    status         TEXT NOT NULL DEFAULT 'active',  -- active | inactive | deleted
    created_by     TEXT NOT NULL,             -- 'system' for defaults, user_id otherwise
    created_at     TEXT NOT NULL,
    updated_at     TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_agents_type ON agents(agent_type, created_by);

CREATE TABLE IF NOT EXISTS user_settings (
    user_id    TEXT PRIMARY KEY,
    api_keys   TEXT NOT NULL DEFAULT '{}',    -- json {groq, gemini, openai, serper, google_places}
    updated_at TEXT NOT NULL
);

-- ============================================================================
-- Chat layer — multi-conversation ChatGPT/Claude-style Command Center.
-- A conversation holds many messages. A user message may spawn a mission;
-- the assistant message stores that mission's id and its rendered result.
-- ============================================================================

CREATE TABLE IF NOT EXISTS conversations (
    id          TEXT PRIMARY KEY,
    title       TEXT NOT NULL DEFAULT 'New chat',
    created_by  TEXT NOT NULL,                -- user_id (Phase 1: 'default-user')
    created_at  TEXT NOT NULL,
    updated_at  TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_conversations_user ON conversations(created_by, updated_at DESC);

CREATE TABLE IF NOT EXISTS messages (
    id              TEXT PRIMARY KEY,
    conversation_id TEXT NOT NULL,
    role            TEXT NOT NULL,            -- user | assistant
    content         TEXT NOT NULL DEFAULT '', -- the text (user prompt or assistant summary)
    mission_id      TEXT,                      -- set on assistant messages that ran a mission
    attachments     TEXT NOT NULL DEFAULT '[]',  -- json array [{name, size, document_id, chunks}]
    outputs         TEXT NOT NULL DEFAULT '[]',  -- json array of mission output cards
    status          TEXT NOT NULL DEFAULT 'done', -- done | running | failed
    created_at      TEXT NOT NULL,
    FOREIGN KEY (conversation_id) REFERENCES conversations(id)
);

CREATE INDEX IF NOT EXISTS idx_messages_conv ON messages(conversation_id, created_at);

-- Global context: a small set of durable facts/preferences injected into every
-- chat for a user. NOT full history — just key/value facts worth remembering.
CREATE TABLE IF NOT EXISTS global_context (
    id          TEXT PRIMARY KEY,
    user_id     TEXT NOT NULL,
    key         TEXT NOT NULL,
    value       TEXT NOT NULL,
    created_at  TEXT NOT NULL,
    updated_at  TEXT NOT NULL,
    UNIQUE(user_id, key)
);

CREATE INDEX IF NOT EXISTS idx_global_context_user ON global_context(user_id);
